#include "PID.h"
#include "stm32f10x.h" // Device header

/**
 * @brief  PID 控制算法更新计算函数
 * @param  P 指向 PID 控制器结构体的指针
 * @retval 无
 * @details 
 *         通过位置式 PID 公式对控制对象进行计算输出。
 *         1. 更新历史误差：将当前误差滚动更新给上次误差，用于计算微分项（斜率）。
 *         2. 计算当前误差：偏差 = 设定目标值 - 当前反馈实际值。
 *         3. 积分项计算：进行偏差累加，若未启用积分（Ki=0）则强制清零以防积分饱和或数据异常。
 *         4. 核心计算公式：输出 = 比例项(Kp * 偏差) + 积分项(Ki * 累积分数) + 微分项(Kd * 偏差变化量)。
 *         5. 输出限幅：控制计算输出在电机的安全最大值/最小值区间内，起到过载保护作用。
 */
void Pid_Update(Pid_t *P)
{
    /* 1. 滚动更新误差历史：保存当前周期的误差作为上一周期的历史，计算微分项时求导使用 */
    P->Error1 = P->Error0;             

    /* 2. 计算当前周期偏差：目标输入与实际输出 the 差值，作为PID调节源头 */
    P->Error0 = P->Target - P->Actual; 

    /* 3. 积分项累加（包含Ki为零时的保护机制）：
     * 当积分常数 Ki 不为零时，累加历史偏差用于消除系统的静态误差。
     * 当 Ki 设定为 0 时，说明不采用积分调节，立刻将累加值清零，防止突然切回 Ki 时引入历史误差造成剧烈抖动。
     */
    if (P->Ki != 0) 
    {
        P->ErrorInt += P->Error0;      // 积分项误差累加
    }
    else 
    {
        P->ErrorInt = 0;               // 积分清零保护
    }

    /* 4. 位置式 PID 核心计算公式：
     * - 比例项（Kp * Error0）：由当前偏差大小决定，偏差越大调节力度越大，反应最迅速。
     * - 积分项（Ki * ErrorInt）：由历史偏差累积决定，用于慢慢消除由于摩擦力、重力等造成的稳态静差。
     * - 微分项（Kd * (Error0 - Error1)）：由偏差变化趋势决定，起到超前预测和阻尼刹车的作用，抑制超调。
     */
    P->Out = P->Kp * P->Error0 + P->Ki * P->ErrorInt + P->Kd * (P->Error0 - P->Error1);

    /* 5. 输出限幅保护：防止计算出的 PWM 值超出硬件电机的驱动极限（通常为 -100 到 100 之间），避免电机饱和失控 */
    if (P->Out > P->OutMax)
    {
        P->Out = P->OutMax;            // 限制输出不能超过设定的最大正向驱动限制
    } 
    if (P->Out < P->OutMin)
    {
        P->Out = P->OutMin;            // 限制输出不能低于设定的反向驱动限制
    } 
}
